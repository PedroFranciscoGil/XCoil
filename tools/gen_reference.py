"""Generate docs/reference.md (every command-line option, public function, config field, solver-budget key and
environment variable of XCoil) from the code.

    python tools/gen_reference.py            # write docs/reference.md
    python tools/gen_reference.py --check    # exit 1 if docs/reference.md is out of date

Descriptions: argparse help texts, docstrings and xcoil/options.py. tests/test_reference.py fails when something
is undocumented or this file is stale.
"""
import argparse
import dataclasses
import importlib
import inspect
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)
os.environ.setdefault("JAX_PLATFORMS", "cpu")
OUT = os.path.join(ROOT, "docs", "reference.md")


def cell(s):
    """Markdown table cell: one line, | escaped."""
    return " ".join(str(s).split()).replace("|", "\\|")


def fmt_default(v):
    if v is inspect.Parameter.empty:
        return "required"
    if isinstance(v, float):
        return f"`{v:g}`"
    if isinstance(v, str):
        return f"`'{v}'`" if v else "`''`"
    return f"`{cell(repr(v))}`"


def first_paragraph(doc):
    doc = inspect.cleandoc(doc or "")
    return doc.split("\n\n")[0]


def cli_section(prog, parser):
    out = [f"### `{prog}`\n\n{cell(first_paragraph(parser.description or ''))}\n\n",
           "| option | default | description |\n|---|---|---|\n"]
    for a in parser._actions:
        if isinstance(a, argparse._HelpAction):
            continue
        flags = ", ".join(f"`{s}`" for s in a.option_strings) or f"`{a.dest}`"
        d = a.default
        dflt = "" if d in (None, argparse.SUPPRESS) or isinstance(a, argparse._StoreFalseAction) else fmt_default(d)
        if isinstance(a, argparse._StoreTrueAction):
            dflt = "off"
        choices = f" Choices: {', '.join(map(str, a.choices))}." if a.choices else ""
        out.append(f"| {flags} | {dflt} | {cell((a.help or '') % {'default': d} if a.help else '')}{choices} |\n")
    return "".join(out) + "\n"


def api_section():
    from xcoil.options import PUBLIC_API
    out = []
    for mod, names in PUBLIC_API:
        m = importlib.import_module(mod)
        out.append(f"### `{mod}`\n\n")
        for n in names:
            obj = getattr(m, n)
            try:
                sig = str(inspect.signature(obj))
            except (TypeError, ValueError):
                sig = "(...)"
            sig = re.sub(r"<function (\w+)[^>]*>", r"\1", sig)
            out.append(f"**`{n}{sig}`**\n\n{inspect.cleandoc(obj.__doc__ or '')}\n\n")
    return "".join(out)


def hconfig_section():
    from xcoil.homotopy.config import HConfig
    from xcoil.options import HCONFIG_DOC
    f = {x.name: x for x in dataclasses.fields(HConfig)}
    out = ["| field | default | units | description |\n|---|---|---|---|\n"]
    for k, (units, desc) in HCONFIG_DOC.items():
        out.append(f"| `{k}` | {fmt_default(f[k].default)} | {units} | {cell(desc)} |\n")
    out.append("\n")
    return "".join(out)


def budget_section():
    from xcoil.fixed.device_lm import DEFAULTS
    from xcoil.fixed.device_lm import MAIN
    from xcoil.options import BUDGET_DOC
    out = ["| key | solve_all value | description |\n|---|---|---|\n"]
    vals = dict(DEFAULTS, **MAIN)
    for k, desc in BUDGET_DOC.items():
        out.append(f"| `{k}` | {fmt_default(vals[k]) if k in vals else ''} | {cell(desc)} |\n")
    return "".join(out) + "\n"


def env_section():
    from xcoil.options import ENV_DOC
    out = ["| variable | description |\n|---|---|\n"]
    for k, desc in ENV_DOC.items():
        out.append(f"| `{k}` | {cell(desc)} |\n")
    return "".join(out) + "\n"


def render():
    from xcoil import cli, check
    from xcoil.options import HCONFIG_DOC, BUDGET_DOC, ENV_DOC, PUBLIC_API
    n_cli = sum(1 for p in (cli.build_parser(), check.build_parser()) for a in p._actions
                if not isinstance(a, argparse._HelpAction))
    n_api = sum(len(v) for _, v in PUBLIC_API)
    head = f"""# Reference

<!-- generated by tools/gen_reference.py from the code; do not edit by hand -->

Every command-line option, public function, problem setting, solver-budget key and environment variable of XCoil:
{n_cli} command-line options, {n_api} public functions and classes, {len(HCONFIG_DOC)} problem settings, {len(BUDGET_DOC)}
solver-budget keys and {len(ENV_DOC)} environment variables. Generated from the code (`python tools/gen_reference.py`);
a test fails when something is added without documentation. What the constraints mean: [constraints.md](constraints.md).

- [Command line](#command-line)
- [Python API](#python-api)
- [Problem settings (HConfig)](#problem-settings-hconfig)
- [Solver budget](#solver-budget)
- [Environment variables](#environment-variables)

## Command line

"""
    return (head + cli_section("xcoil-coils", cli.build_parser()) + cli_section("xcoil-check", check.build_parser())
            + "## Python API\n\n" + api_section()
            + "## Problem settings (HConfig)\n\n`xcoil.homotopy.config.HConfig`, the frozen settings of a coil problem. "
              "`make_problem` fills the problem fields from its arguments; the rest keep these defaults.\n\n"
            + hconfig_section()
            + "## Solver budget\n\nThe `budget` dict of `device_lm.build_solver`. `solve_all` uses "
              "`device_lm.MAIN`, completed by `device_lm.DEFAULTS`; the column shows that value.\n\n"
            + budget_section()
            + "## Environment variables\n\nRead when xcoil is imported; set them before.\n\n" + env_section())


if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args()
    txt = render()
    if a.check:
        cur = open(OUT).read() if os.path.exists(OUT) else ""
        if cur != txt:
            print("docs/reference.md is out of date: run python tools/gen_reference.py")
            sys.exit(1)
        print("docs/reference.md is up to date")
    else:
        open(OUT, "w").write(txt)
        print("wrote", OUT)
